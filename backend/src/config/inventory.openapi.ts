const ref = (name: string) => ({ $ref: `#/components/schemas/${name}` });
const json = (schema: object, example?: object) => ({
  'application/json': { schema, ...(example ? { example } : {}) },
});
const error = (description: string) => ({ description, content: json(ref('Error')) });
const id = {
  type: 'string',
  pattern: '^[1-9][0-9]{0,19}$',
  description: 'Unsigned BIGINT decimal string',
  example: '1',
};
const timestamp = { type: 'string', format: 'date-time' };

const security = [{ bearerAuth: [] }];
const csrf = {
  name: 'X-CSRF-Protection',
  in: 'header',
  required: true,
  description: 'Required custom header for CSRF protection on mutating requests.',
  schema: { type: 'string', enum: ['1'], default: '1' },
};
const idParam = { name: 'id', in: 'path', required: true, schema: id };

const pageParam = {
  name: 'page',
  in: 'query',
  required: false,
  schema: { type: 'integer', minimum: 1, default: 1 },
};
const limitParam = {
  name: 'limit',
  in: 'query',
  required: false,
  schema: { type: 'integer', minimum: 1, maximum: 100, default: 20 },
};

const envelope = (data: object) => ({
  type: 'object',
  required: ['success', 'message', 'data'],
  properties: {
    success: { type: 'boolean', enum: [true] },
    message: { type: 'string' },
    data,
  },
});

const pageEnvelope = (itemSchema: object) => ({
  type: 'object',
  required: ['success', 'message', 'data'],
  properties: {
    success: { type: 'boolean', enum: [true] },
    message: { type: 'string' },
    data: {
      type: 'object',
      required: ['items', 'pagination'],
      properties: {
        items: { type: 'array', items: itemSchema },
        pagination: {
          type: 'object',
          required: ['page', 'limit', 'total', 'totalPages'],
          properties: {
            page: { type: 'integer' },
            limit: { type: 'integer' },
            total: { type: 'integer' },
            totalPages: { type: 'integer' },
          },
        },
      },
    },
  },
});

